#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';

export async function syncAstryxCatalog() {
  const pkgRoot = path.resolve(import.meta.dirname, '..');
  const componentsRoot = path.resolve(pkgRoot, '../astryx/src/components');
  const outPath = path.join(pkgRoot, 'src/astryx-catalog.generated.ts');

  const dirs = fs
    .readdirSync(componentsRoot, {withFileTypes: true})
    .filter(d => d.isDirectory())
    .map(d => d.name)
    .sort((a, b) => a.localeCompare(b));

  const entries = [];
  for (const dirName of dirs) {
    const docPath = path.join(componentsRoot, dirName, `${dirName}.doc.mjs`);
    if (!fs.existsSync(docPath)) continue;
    const mod = await import(`${pathToFileURL(docPath).href}?t=${Date.now()}`);
    const doc = mod.default ?? {};
    const props = Array.isArray(doc.props)
      ? doc.props.map(p => ({
          name: String(p.name ?? ''),
          type: String(p.type ?? 'unknown').replace(/\s+/g, ' ').trim(),
          required: Boolean(p.required),
        }))
      : [];
    const rawDesc = String(doc.usage?.description ?? '').replace(/\s+/g, ' ').trim();
    const summary =
      rawDesc.split(/(?<!\bvs|\be\.g|\bi\.e|\betc)(?<=\.)\s+/i)[0] || rawDesc;
    entries.push({
      name: String(doc.name ?? dirName),
      category: String(doc.category ?? 'General'),
      summary,
      props,
    });
  }

  const fileSource = `// AUTO-GENERATED by scripts/sync-astryx-catalog.mjs during \`pnpm build\` — DO NOT EDIT MANUALLY.
export interface MehanAstryxCatalogProp {
  readonly name: string;
  readonly type: string;
  readonly required: boolean;
}

export interface MehanAstryxCatalogEntry {
  readonly name: string;
  readonly category: string;
  readonly summary: string;
  readonly props: readonly MehanAstryxCatalogProp[];
}

export const MEHAN_ASTRYX_CATALOG: readonly MehanAstryxCatalogEntry[] = ${JSON.stringify(
    entries,
    null,
    2,
  )};
`;

  const prev = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
  if (prev !== fileSource) {
    fs.writeFileSync(outPath, fileSource, 'utf8');
  }
  return entries.length;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const count = await syncAstryxCatalog();
  console.log(`✅ Synced ${count} @mehan/astryx components into src/astryx-catalog.generated.ts`);
}
